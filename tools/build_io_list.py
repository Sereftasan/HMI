#!/usr/bin/env python3
"""
Builds <machine>/IoList.csv - the machine's physical INPUTS and OUTPUTS for the
HMI's "Inputs / Outputs" side page - from the engineer's device list and the
PLC's I/O interface block (see io_mirror_map.py).

Each point is listed by its PHYSICAL address (X20, Y0: what the electrician
reads on the drawing) with the device the HMI actually READS: the internal
relay the PLC copies it into (M200), because the screens bind to the mirrors,
never to X or Y (io_mirror_map.py says why). A point the interface block does
not copy has no mirror; the page then reads the physical address itself.

Input : tools/FA2010_DeviceList.xls, sheet PLC_Labels - X address / label in
        columns G/H, Y address / label in columns J/K.
Output: Label;Kind;Address;Read;Plc      (Kind = Input | Output, Plc = the
        module's own PLC number)

Usage:
    python3 tools/build_io_list.py            (FA2010)
"""
import io, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from io_mirror_map import build as build_mirror_map, parse, octal_add, FA2010_ST

HERE = os.path.dirname(os.path.abspath(__file__))


def points_from_device_list(path):
    import xlrd
    sheet = xlrd.open_workbook(path).sheet_by_name('PLC_Labels')
    points = []
    for r in range(sheet.nrows):
        for col_addr, col_label, kind in ((6, 7, 'Input'), (9, 10, 'Output')):
            if sheet.ncols <= col_label:
                continue
            addr = str(sheet.cell_value(r, col_addr)).strip().upper()
            label = str(sheet.cell_value(r, col_label)).strip()
            if len(addr) > 1 and addr[0] in 'XY' and all(ch in '01234567' for ch in addr[1:]):
                points.append((label, kind, addr))
    return points


def main():
    machine = os.path.join(HERE, '..', 'Kaban.Machines.FA2010')
    points = points_from_device_list(os.path.join(HERE, 'FA2010_DeviceList.xls'))
    mirror, warnings = build_mirror_map()
    for w in warnings:
        print('WARNING:', w)
    # A relay written by TWO points holds the LAST one's state (the PLC runs the
    # statements in order): the other point is read at its own address instead.
    owner = {}
    for m_base, letter, io_base, count in parse(FA2010_ST):
        for i in range(count):
            owner['M' + str(m_base + i)] = letter + octal_add(io_base, i)
    shared = [pt for pt, m in mirror.items() if owner.get(m) != pt]
    for pt in shared:
        del mirror[pt]
    if shared:
        print('read at their own address (their relay is overwritten):', ', '.join(sorted(shared)))
    points.sort(key=lambda p: (p[2][0], int(p[2][1:], 8)))
    lines = [
        '# Kaban HMI inputs and outputs - generated by tools/build_io_list.py',
        '# Address: the physical point. Read: the relay the PLC copies it into, which',
        '# the HMI reads (empty: the point itself). Plc: the machine\'s own PLC number.',
        'Label;Kind;Address;Read;Plc',
    ]
    unmirrored = 0
    for label, kind, addr in points:
        read = mirror.get(addr, '')
        if not read:
            unmirrored += 1
        lines.append(';'.join((label.replace(';', ','), kind, addr, read, '1')))
    out = os.path.join(machine, 'IoList.csv')
    with io.open(out, 'w', encoding='utf-8', newline='\r\n') as f:
        f.write('\n'.join(lines) + '\n')
    print('%s: %d points (%d inputs, %d outputs), %d without a mirror' % (
        out, len(points), sum(1 for p in points if p[1] == 'Input'),
        sum(1 for p in points if p[1] == 'Output'), unmirrored))


if __name__ == '__main__':
    main()
