#!/usr/bin/env python3
"""
Builds <machine>/PlcLabels.csv from the engineer's device list.

The PLC copies its physical I/O into internal relays in an ST interface block
(K2M200:=K2X20; ...) so the machine can be re-wired without touching a screen.
This script performs that TRANSLATION so the HMI never has to: a device listed at
X20 is written out as M200, and the running program only ever sees addresses it
can bind to. There is no "mirror" concept anywhere in the HMI - the substitution
happens here, once, while the file is built.

Input : a TAB or ;-separated list exported from GX Works / Excel -
            Label <tab> DataType <tab> Address        (Address may be X/Y or M/D/...)
Output: Label;DataType;Address                        (X/Y already translated)

Usage:
    python3 tools/build_plc_labels.py FA2010_labels.txt Kaban.Machines.FA2010
"""
import sys, os, io
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from io_mirror_map import build as build_mirror_map


def read_list(path):
    rows = []
    with io.open(path, encoding='utf-8-sig') as f:
        for raw in f:
            line = raw.rstrip('\r\n')
            if not line.strip():
                continue
            parts = line.split('\t') if '\t' in line else line.split(';')
            parts = [p.strip() for p in parts]
            if len(parts) < 2:
                continue
            label = parts[0]
            dtype = parts[1] if len(parts) > 1 else 'Bit'
            addr = parts[2] if len(parts) > 2 else ''
            if label.lower() == 'label':
                continue
            rows.append((label, dtype, addr))
    return rows


def main():
    if len(sys.argv) < 3:
        print(__doc__)
        return 1
    src, project = sys.argv[1], sys.argv[2]
    rows = read_list(src)
    mirror, warnings = build_mirror_map()

    out = os.path.join(project, 'PlcLabels.csv')
    physical = translated = unassigned = 0
    untranslated = []
    with io.open(out, 'w', encoding='utf-8-sig', newline='') as f:
        f.write('# Kaban HMI PLC label list - generated by tools/build_plc_labels.py\r\n')
        f.write('# Physical X/Y devices have ALREADY been translated to the internal\r\n')
        f.write('# relay the PLC copies them into, so every address here is one the\r\n')
        f.write('# HMI can bind to directly.\r\n')
        f.write('Label;DataType;Address\r\n')
        for label, dtype, addr in rows:
            a = addr.upper()
            if a.startswith('X') or a.startswith('Y'):
                physical += 1
                m = mirror.get(a, '')
                if m:
                    translated += 1
                    # the ORIGINAL physical address is kept only as a comment, so an
                    # engineer can still trace a device back to the terminal
                    f.write('%s;%s;%s\r\n' % (label, dtype, m))
                    continue
                untranslated.append((label, dtype, addr))
                # not in the interface block: leave it out rather than emit an address
                # the HMI cannot read - it would fail silently on the machine
                continue
            if not addr:
                unassigned += 1
                continue
            f.write('%s;%s;%s\r\n' % (label, dtype, addr))

    print('%s: %d labels in, %d physical (%d translated), %d skipped with no address'
          % (out, len(rows), physical, translated, unassigned))
    for w in warnings:
        print('  ST INTERFACE WARNING:', w)
    if untranslated:
        print('  %d physical points are NOT copied by the ST block and were LEFT OUT'
              % len(untranslated))
        print('  (the HMI cannot read X/Y directly, so binding to them would fail silently):')
        for label, dtype, addr in untranslated[:12]:
            print('     %-8s %s' % (addr, label))
    return 0


if __name__ == '__main__':
    sys.exit(main())

