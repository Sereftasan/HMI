#!/usr/bin/env python3
"""
Builds the AXIS SETTINGS page: one AxisSettingHMI per axis.

Axis parameters follow a naming convention rather than living together, so the
axis is discovered from the labels and its fields collected from wherever they
happen to sit:

    MAN__X1_Geri / _Ileri   jog
    X1_AktPoz               position
    PC_X_MIN / PC_X_MAX     travel limits, often shared by both X axes
    PC_X1_HOME              reference value
    PC_X1_KalibreDegeri     calibration value
    PC_X1_KalibreEt         calibrate command

A field with no matching label is left EMPTY, and the control simply does not
draw it. H800 has no go-to-reference command and no current or Z-distance words,
so those columns are blank on its rows - which is the honest picture.
"""
import os, re, sys, collections
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from machine_pages import load_labels, is_32

ROOT = os.path.join(HERE, "..")

HDR = '''\ufeff// <auto-generated>
//   Generated by tools/build_axis_pages.py from {m}/PlcLabels.csv
//
//   One AxisSettingHMI per axis. A field whose device is empty is not drawn -
//   see the control's own notes.
// </auto-generated>
using System.Windows.Forms;

namespace Kaban.Machines.{m}.Screens
{{
    public partial class AxisSettings : UserControl
    {{
        public AxisSettings()
        {{
            this.AutoScroll = true;
            this.BackColor = System.Drawing.Color.White;
            this.Size = new System.Drawing.Size(1060, 700);
            this.SuspendLayout();

            int y = 8;
            this.Controls.Add(Kaban.UI.Controls.AxisSettingHMI.BuildHeader(y));
            y += 30;

'''

ROW = '''            var {var} = new Kaban.UI.Controls.AxisSettingHMI
            {{
                PlcNumber = 1,
                SectionName = "{section}",
                AxisName = "{axis}",
                CommandBackAddress = "{back}",
                CommandForwardAddress = "{fwd}",
                PositionAddress = "{pos}",
                PositionDataType = Kaban.Core.Enums.DataTypeEnum.{posdt},
                BacklashAddress = "{backlash}",
                MinLimitAddress = "{min}",
                MaxLimitAddress = "{max}",
                ReferenceAddress = "{home}",
                CalibrationAddress = "{calval}",
                CalibrateAddress = "{calcmd}",
                GoToReferenceAddress = "{goref}",
                CurrentAddress = "{current}",
                ZDistanceAddress = "{zdist}",
                SettingDataType = Kaban.Core.Enums.DataTypeEnum.{setdt},
                Divisor = 10000D,
                DecimalPlaces = 2,
                Digits = 8,
                Suffix = "mm",
                RequiredSecurity = Kaban.Core.Enums.SecurityLevel.Maintenance
            }};
            {var}.Location = new System.Drawing.Point(8, y);
            {var}.BuildRow();
            this.Controls.Add({var});
            y += Kaban.UI.Controls.AxisSettingHMI.RowHeight + 4;

'''

FTR = '''            this.ResumeLayout(false);
        }
    }
}
'''

def collect(rows):
    """{axis: {field: address}} - fields found wherever the naming puts them."""
    axes = collections.OrderedDict()

    def slot(axis, key, addr):
        axes.setdefault(axis, {}).setdefault(key, addr)

    for r in rows:
        lab, addr = r["label"], r["addr"]

        m = re.match(r"^MAN__?([XYZ]\d?)_(Ileri|Geri)$", lab)
        if m: slot(m.group(1), "fwd" if m.group(2) == "Ileri" else "back", addr); continue

        m = re.match(r"^([XYZ]\d?)_AktPoz$", lab)
        if m: slot(m.group(1), "pos", addr); continue

        m = re.match(r"^PC_([XYZ]\d?)_HOME$", lab, re.I)
        if m: slot(m.group(1), "home", addr); continue

        m = re.match(r"^PC_([XYZ]\d?)_KalibreDegeri$", lab, re.I)
        if m: slot(m.group(1), "calval", addr); continue

        m = re.match(r"^PC_([XYZ]\d?)_KalibreEt$", lab, re.I)
        if m: slot(m.group(1), "calcmd", addr); continue

        m = re.match(r"^PC_([XYZ]\d?)_(MIN|MAX)$", lab, re.I)
        if m: slot(m.group(1), m.group(2).lower(), addr); continue

        m = re.match(r"^PC_([XYZ]\d?)_(Bosluk|Backlash)$", lab, re.I)
        if m: slot(m.group(1), "backlash", addr); continue

        m = re.match(r"^PC_([XYZ]\d?)_(RefGonder|GoToRef|ReferansGonder)$", lab, re.I)
        if m: slot(m.group(1), "goref", addr); continue

        m = re.match(r"^([XYZ]\d?)_(Akim|Current|Yuk|Load)$", lab, re.I)
        if m: slot(m.group(1), "current", addr); continue

    # A limit written PC_X_MIN with no digit applies to every X axis: the machine
    # shares one travel limit between X1 and X2. Fill it down rather than leaving
    # the numbered axes blank.
    for axis in list(axes):
        base = axis[0]
        if base in axes and axis != base:
            for k in ("min", "max", "backlash"):
                if k not in axes[axis] and k in axes[base]:
                    axes[axis][k] = axes[base][k]

    # drop the bare-letter pseudo axis once its values are distributed
    for base in ("X", "Y", "Z"):
        if base in axes and any(a != base and a.startswith(base) for a in axes):
            del axes[base]
    return axes

def section_of(axis):
    n = axis[1:] or "1"
    return "Unit " + n

def build(machine):
    src = os.path.join(ROOT, "Kaban.Machines." + machine, "PlcLabels.csv")
    if not os.path.exists(src):
        print("  %s: no label list" % machine); return False
    axes = collect(load_labels(src))
    if not axes:
        print("  %s: no axes found" % machine); return False

    rows_dt = {r["addr"]: r["dtype"] for r in load_labels(src)}
    body = ""
    for axis, f in axes.items():
        pos = f.get("pos", "")
        setaddr = f.get("home") or f.get("min") or ""
        body += ROW.format(
            var="ax" + axis, section=section_of(axis), axis=axis,
            back=f.get("back", ""), fwd=f.get("fwd", ""), pos=pos,
            posdt="Bin_32" if is_32(rows_dt.get(pos, "Double")) else "Bin_16",
            backlash=f.get("backlash", ""), min=f.get("min", ""), max=f.get("max", ""),
            home=f.get("home", ""), calval=f.get("calval", ""),
            calcmd=f.get("calcmd", ""), goref=f.get("goref", ""),
            current=f.get("current", ""), zdist=f.get("zdist", ""),
            setdt="Bin_32" if is_32(rows_dt.get(setaddr, "Double")) else "Bin_16")

    out = os.path.join(ROOT, "Kaban.Machines." + machine, "Screens")
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, "AxisSettings.cs"), "w", encoding="utf-8", newline="\r\n") as fh:
        fh.write(HDR.format(m=machine) + body + FTR)
    filled = sum(1 for a in axes.values() for k, v in a.items() if v)
    print("  %s: %d axes, %d fields bound" % (machine, len(axes), filled))
    return True

if __name__ == "__main__":
    for m in sys.argv[1:] or ["H800", "H500", "MD3020", "FA2010"]:
        build(m)

