-- =====================================================================
-- 2. PROFILE CATALOGUE
-- =====================================================================

CREATE TABLE profile_vendor (
    id      INTEGER PRIMARY KEY,
    code    TEXT NOT NULL UNIQUE,                -- REY, SCH, ALM
    name    TEXT NOT NULL
);

CREATE TABLE profile_series (
    id              INTEGER PRIMARY KEY,
    vendor_id       INTEGER NOT NULL REFERENCES profile_vendor(id) ON DELETE CASCADE,
    code            TEXT NOT NULL,               -- ML8, AWS75
    name            TEXT NOT NULL,
    material        TEXT NOT NULL,                         -- allowed: PVC,ALU,WOOD,COMPOSITE
    system_depth_mm REAL,
    UNIQUE (vendor_id, code)
);

-- A series variant (Functional / Hidden Vent / HI ...). Optional: a series with
-- no variants simply has one row, so the hierarchy never has a hole in it.
CREATE TABLE profile_variant (
    id              INTEGER PRIMARY KEY,
    series_id       INTEGER NOT NULL REFERENCES profile_series(id) ON DELETE CASCADE,
    code            TEXT NOT NULL,
    name            TEXT NOT NULL,
    UNIQUE (series_id, code)
);

-- FUNCTION group: what the profile IS (frame, sash, mullion...).
CREATE TABLE profile_group (
    id              INTEGER PRIMARY KEY,
    variant_id      INTEGER NOT NULL REFERENCES profile_variant(id) ON DELETE CASCADE,
    name            TEXT NOT NULL,
    profile_type    TEXT NOT NULL,                         -- allowed: FRAME,SASH,MULLION,TRANSOM,DOOR_LEAF,BEAD,ADAPTER,REINFORCEMENT,CONNECTION,SILL,
    hardware_interface_id INTEGER REFERENCES hardware_interface(id),

    default_width_mm  REAL,
    default_height_mm REAL,

    -- The measured, human-confirmed member of the group. A new profile's
    -- extracted datums are compared against it, and the distance is recorded on
    -- every placement (§7 deviation_mm) - which is how a profile that has been
    -- put in the wrong group gets caught before it is cut rather than after.
    reference_profile_id INTEGER,
    UNIQUE (variant_id, name)
);

-- MACHINING family: how the profile is PROCESSED. Deliberately independent of
-- profile_group, because the two genuinely differ - a Reynaers frame and a
-- Schueco frame can share an outside-drainage machining family while belonging
-- to different function groups, series and vendors.
CREATE TABLE machining_family (
    id      INTEGER PRIMARY KEY,
    code    TEXT NOT NULL UNIQUE,                -- AL_FRAME_70_OUTSIDE
    name    TEXT NOT NULL,
    note    TEXT
);

CREATE TABLE profile (
    id                  INTEGER PRIMARY KEY,
    group_id            INTEGER NOT NULL REFERENCES profile_group(id) ON DELETE RESTRICT,
    machining_family_id INTEGER REFERENCES machining_family(id),

    code                TEXT NOT NULL,
    description         TEXT,

    -- Inheritance between individual profiles: a variant that differs from
    -- another by two numbers should not restate the other twenty.
    base_profile_id     INTEGER REFERENCES profile(id) ON DELETE SET NULL,

    width_mm            REAL,                    -- NULL -> group default -> base
    height_mm           REAL,

    dxf_path            TEXT,
    dxf_hash            TEXT,                    -- catches a silently replaced file
    dxf_status          TEXT NOT NULL DEFAULT 'NONE',      -- allowed: NONE,IMPORTED,PROPOSED,CONFIRMED,

    is_active           INTEGER NOT NULL DEFAULT 1,
    created_at          TEXT NOT NULL,
    created_by          TEXT,
    UNIQUE (group_id, code)
);
CREATE INDEX ix_profile_group ON profile(group_id);
CREATE INDEX ix_profile_family ON profile(machining_family_id);

-- The datums of ONE profile, in its own normalised coordinates.
CREATE TABLE profile_reference (
    id              INTEGER PRIMARY KEY,
    profile_id      INTEGER NOT NULL REFERENCES profile(id) ON DELETE CASCADE,
    reference_code  TEXT NOT NULL REFERENCES reference_type(code),
    y_mm            REAL NOT NULL,
    z_mm            REAL NOT NULL,
    source          TEXT NOT NULL,                         -- allowed: DXF_LAYER,DXF_MARKER,DXF_GEOMETRY,AI_PROPOSED,MANUAL,INHERITED,
    confidence      REAL,                        -- 0..1, meaningful for AI_PROPOSED
    confirmed_by    TEXT,
    confirmed_at    TEXT,
    UNIQUE (profile_id, reference_code)
);

-- =====================================================================
-- 3. PROFILE GEOMETRY DERIVED FROM THE DXF
-- =====================================================================
-- Material/air intervals along a machining direction. This is GEOMETRY, so it
-- belongs here; the feed rate to use in each interval is a machine decision and
-- does not (§11).
--
-- Stored as intervals rather than named "levels" because different operations
-- approach from different directions, and a fixed level list only answers for
-- one of them.

CREATE TABLE material_interval (
    id              INTEGER PRIMARY KEY,
    profile_id      INTEGER NOT NULL REFERENCES profile(id) ON DELETE CASCADE,
    direction       TEXT NOT NULL,                         -- allowed: Y,Z,X
    entry_side      TEXT NOT NULL,                         -- allowed: OUTSIDE,INSIDE,TOP,BOTTOM,END
    -- the ray this interval list was computed along
    ray_y_mm        REAL,
    ray_z_mm        REAL,
    seq             INTEGER NOT NULL,
    start_mm        REAL NOT NULL,
    end_mm          REAL NOT NULL,
    state           TEXT NOT NULL,                         -- allowed: MATERIAL,AIR
    wall_thickness_mm REAL,                      -- MATERIAL only; drives thin-wall care
    UNIQUE (profile_id, direction, entry_side, ray_y_mm, ray_z_mm, seq)
);
CREATE INDEX ix_interval_profile ON material_interval(profile_id);

