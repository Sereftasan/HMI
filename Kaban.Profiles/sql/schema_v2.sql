-- =====================================================================
--  KABAN - PROFILE & ACCESSORY LIBRARY   (schema v2)
--
--  THIS DATABASE KNOWS NOTHING ABOUT MACHINES.
--  ------------------------------------------
--  No tools, no feeds, no spindle speeds, no G-code, no station numbers, no
--  machine coordinates. It describes PROFILES, ACCESSORIES and WHERE an
--  accessory sits on a profile - facts that are true of a Reynaers ML8 frame
--  whichever machine is cutting it, or none at all.
--
--  Everything machine-specific lives in a SEPARATE machine-side schema that
--  references these ids (see §11). That split is the point: FA2010 opens this
--  library under its Profiles page today, and when SB3012 or a future machine
--  needs the same profiles with different tools and feeds, it references the
--  same rows instead of copying them.
--
--  A useful test when adding a column here: "would this still be true if we
--  sold no machines at all?" If not, it belongs in the machine-side schema.
--
--  PROVIDER PORTABILITY (EF Core: SQLite now, PostgreSQL / SQL Server later)
--  --------------------------------------------------------------------
--  This file is the SQLite rendering of the EF Core model in
--  `Kaban.Profiles/Model`. It is GENERATED FROM that model, not maintained
--  beside it - two hand-kept definitions of the same tables drift, and the one
--  that drifts silently is always the SQL.
--
--  Rules the model obeys so the same entities emit valid DDL on all three:
--    * no        EF maps identity per provider (IDENTITY /
--                             GENERATED BY DEFAULT / rowid)
--    * no datetime('now')     defaults are set in C#; each provider spells
--                             "now" differently (GETUTCDATE / now() / datetime)
--    * no,                                                -- allowed: ...  enumerations are C# enums persisted as short
--                             strings and validated in the model. All three
--                             providers accept CHECK, but EF cannot round-trip
--                             it, so the rule would live in the SQL and not in
--                             the model - and only one of them gets updated
--    * no TRIGGER             history rows are written by the repository, so
--                             the behaviour is testable and identical
--                             everywhere. Trigger syntax is not portable
--    * no VIEW                the two views are LINQ queries on the context
--    * TEXT / REAL / INTEGER  map cleanly to text / double precision / integer
--
--  COORDINATES
--  -----------
--  Every Y/Z in this file is in the PROFILE's own normalised system:
--      origin  OUTSIDE_SURFACE x BED_DATUM
--      Y+      toward the inside
--      Z+      up
--  Machine coordinates are obtained by the machine layer applying its own
--  fixture transform. This database never stores a machine coordinate.
-- =====================================================================

PRAGMA foreign_keys = ON;

