-- =====================================================================
-- 11. WHAT IS DELIBERATELY *NOT* HERE
-- =====================================================================
-- The machine layer owns these, in its own schema, referencing profile ids:
--
--   mounted_tool          which cutters are in which spindle, diameters, lengths
--   tool_capability       what each tool may cut, in which material
--   feed_strategy         feed/speed per material state and wall thickness
--   machine_fixture       profile space -> machine coordinates
--   post_processor        controller dialect, incremental output
--   nc_program            generated programs and their history
--
-- A feed rate is a property of a machine, a tool and a material - not of a
-- Reynaers frame. Putting it here would mean FA2010 and SB3012 could not share
-- a profile without one of them being wrong, which is exactly the coupling this
-- separation exists to prevent.
