-- =====================================================================
-- 5. PARAMETRIC MACROS - shape only, no tool and no G-code
-- =====================================================================
-- A macro says WHAT to make (a 5x30 slot, 6 mm deep). It does not say which
-- cutter, how many passes, at what feed, or in which controller's dialect -
-- all of which depend on the machine and belong in the machine layer.
--
-- Keeping them apart is what lets the same hinge pattern run on a machine with
-- a 6 mm cutter and on one with a 5 mm cutter without a second definition.

CREATE TABLE macro_type (
    code        TEXT PRIMARY KEY,                -- ROUND_HOLE, SLOT, POCKET, CONTOUR
    name        TEXT NOT NULL,
    param_schema TEXT                            -- JSON: which params this type expects
);
INSERT INTO macro_type (code, name, param_schema) VALUES
 ('ROUND_HOLE','Round hole','{"diameter_mm":0,"depth_mm":0}'),
 ('SLOT',      'Slot',      '{"length_mm":0,"width_mm":0,"depth_mm":0,"angle_deg":0}'),
 ('POCKET',    'Pocket',    '{"length_mm":0,"width_mm":0,"depth_mm":0,"corner_r_mm":0}'),
 ('CONTOUR',   'Contour',   '{"path":"","depth_mm":0}');

CREATE TABLE macro (
    id              INTEGER PRIMARY KEY,
    code            TEXT NOT NULL UNIQUE,        -- DRILL_6, SLOT_5X30
    macro_type      TEXT NOT NULL REFERENCES macro_type(code),
    name            TEXT,
    params_json     TEXT NOT NULL,               -- the shape, per param_schema
    -- Advice, not instruction: the machine layer decides the actual strategy.
    through_profile INTEGER NOT NULL DEFAULT 0,  -- depth follows the geometry
    note            TEXT
);

-- =====================================================================
-- 6. ACCESSORY OPERATIONS - an accessory is usually SEVERAL cuts
-- =====================================================================
-- A hinge is three holes and a slot, each at its own offset. v1 of this schema
-- stored one Y/Z per accessory, which could not express that at all.

CREATE TABLE accessory_operation (
    id              INTEGER PRIMARY KEY,
    accessory_id    INTEGER NOT NULL REFERENCES accessory(id) ON DELETE CASCADE,
    macro_id        INTEGER NOT NULL REFERENCES macro(id),
    seq             INTEGER NOT NULL,            -- order within the accessory

    position_mode   TEXT NOT NULL DEFAULT 'REFERENCE_OFFSET' REFERENCES position_mode(code),
    reference_code  TEXT REFERENCES reference_type(code),
    offset_y_mm     REAL NOT NULL DEFAULT 0,
    offset_z_mm     REAL NOT NULL DEFAULT 0,
    ratio           REAL,                        -- RATIO_OF_* modes

    -- Along the bar. Belongs to the operation because a hinge's holes repeat
    -- while its slot does not.
    x_strategy      TEXT NOT NULL DEFAULT 'SINGLE',        -- allowed: SINGLE,FROM_START,FROM_END,CENTRED,DISTRIBUTED,FROM_BOTH_ENDS,
    x_base_mm       REAL DEFAULT 0,
    x_pitch_mm      REAL,
    x_count         INTEGER,

    rotation_deg    REAL NOT NULL DEFAULT 0,
    mirror          INTEGER NOT NULL DEFAULT 0,
    UNIQUE (accessory_id, seq)
);
CREATE INDEX ix_op_accessory ON accessory_operation(accessory_id);

-- =====================================================================
-- 7. ASSIGNMENT AND THE CORRECTION CHAIN
-- =====================================================================
-- Which accessories apply to a profile GROUP. This is the assignment the
-- operator makes once; individual profiles inherit it.

CREATE TABLE group_accessory_assignment (
    id                  INTEGER PRIMARY KEY,
    profile_group_id    INTEGER NOT NULL REFERENCES profile_group(id) ON DELETE CASCADE,
    accessory_id        INTEGER NOT NULL REFERENCES accessory(id) ON DELETE CASCADE,
    is_enabled          INTEGER NOT NULL DEFAULT 1,
    note                TEXT,
    UNIQUE (profile_group_id, accessory_id)
);

-- CORRECTIONS, not replacements.
--
-- A correction is added to what the operation computed; it never overwrites the
-- accessory definition. So fixing one profile cannot silently move the same
-- hinge on ninety others, and re-measuring the accessory later still benefits
-- every profile that was corrected.
--
--   final = reference + operation offset
--         + series correction + group correction + profile correction
--
-- scope_type/scope_id is a deliberate soft key: three scope tables that differ
-- only in one column is worse to query and worse to extend.
CREATE TABLE placement_correction (
    id              INTEGER PRIMARY KEY,
    scope_type      TEXT NOT NULL,                         -- allowed: SERIES,GROUP,PROFILE
    scope_id        INTEGER NOT NULL,
    accessory_id    INTEGER REFERENCES accessory(id) ON DELETE CASCADE,   -- NULL = all
    operation_id    INTEGER REFERENCES accessory_operation(id) ON DELETE CASCADE, -- NULL = all
    correction_y_mm REAL NOT NULL DEFAULT 0,
    correction_z_mm REAL NOT NULL DEFAULT 0,
    reason          TEXT,
    created_by      TEXT,
    created_at      TEXT NOT NULL
);
CREATE INDEX ix_corr_scope ON placement_correction(scope_type, scope_id);

-- =====================================================================
-- 8. RESOLVED PLACEMENTS - what gets read, and what a person confirmed
-- =====================================================================
-- One row per (profile, operation), materialised by the resolver.
--
-- status is the safety mechanism:
--   AUTO       computed from confirmed datums. Fine for simulation, NOT cutting.
--   PROPOSED   computed from AI-extracted datums. Needs review.
--   CONFIRMED  a person checked it against the drawing or a trial cut.
--   REJECTED   does not apply to this profile.

CREATE TABLE resolved_placement (
    id              INTEGER PRIMARY KEY,
    profile_id      INTEGER NOT NULL REFERENCES profile(id) ON DELETE CASCADE,
    operation_id    INTEGER NOT NULL REFERENCES accessory_operation(id) ON DELETE CASCADE,

    y_mm            REAL NOT NULL,
    z_mm            REAL NOT NULL,

    -- kept split so the UI can show "template 14.0, correction +1.0, final 15.0"
    base_y_mm       REAL, base_z_mm REAL,
    corr_y_mm       REAL NOT NULL DEFAULT 0,
    corr_z_mm       REAL NOT NULL DEFAULT 0,

    x_strategy      TEXT, x_base_mm REAL, x_pitch_mm REAL, x_count INTEGER,

    status          TEXT NOT NULL DEFAULT 'AUTO',          -- allowed: AUTO,PROPOSED,CONFIRMED,REJECTED,
    confidence      REAL,
    deviation_mm    REAL,                        -- vs the group's reference profile
    confirmed_by    TEXT,
    confirmed_at    TEXT,
    updated_at      TEXT NOT NULL,
    UNIQUE (profile_id, operation_id)
);
CREATE INDEX ix_resolved_profile ON resolved_placement(profile_id);
CREATE INDEX ix_resolved_status  ON resolved_placement(status);

CREATE TABLE placement_history (
    id              INTEGER PRIMARY KEY,
    placement_id    INTEGER NOT NULL REFERENCES resolved_placement(id) ON DELETE CASCADE,
    y_mm REAL, z_mm REAL, status TEXT,
    changed_by      TEXT,
    changed_at      TEXT NOT NULL,
    reason          TEXT
);

